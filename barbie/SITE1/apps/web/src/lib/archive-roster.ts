const SET = new Set(ARCHIVE_ROSTER_NAMES);

export function normName(s: string): string {
  return (s ?? "").trim().toLowerCase().replace(/ё/g, "е");
}

/** true — имя есть в архиве (реальная модель). */
export function inArchiveRoster(name: string): boolean {
  return SET.has(normName(name));
}
